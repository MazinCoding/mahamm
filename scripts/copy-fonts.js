// Copies the self-hosted IBM Plex fonts out of node_modules so the CSP can
// stay 'self'-only (no Google Fonts). Missing fonts fall back to system fonts.
import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'fonts');
await mkdir(out, { recursive: true });

const faces = [
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', subset: 'latin', range: 'U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD' },
  { family: 'IBM Plex Sans Arabic', pkg: 'ibm-plex-sans-arabic', subset: 'arabic', range: 'U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0898-08E1, U+08E3-08FF, U+200C-200E, U+2010-2011, U+204F, U+2E41, U+FB50-FDFF, U+FE70-FE74, U+FE76-FEFC' },
];
const weights = [400, 500, 600];
let css = '/* Generated by scripts/copy-fonts.js */\n';
let copied = 0;
for (const face of faces) {
  for (const w of weights) {
    const file = `${face.pkg}-${face.subset}-${w}-normal.woff2`;
    const src = path.join(root, 'node_modules', '@fontsource', face.pkg, 'files', file);
    if (!existsSync(src)) continue;
    await copyFile(src, path.join(out, file));
    copied += 1;
    css += `@font-face{font-family:'${face.family}';font-style:normal;font-weight:${w};font-display:swap;src:url(./${file}) format('woff2');unicode-range:${face.range};}\n`;
  }
}
await writeFile(path.join(out, 'fonts.css'), css);
console.log(`fonts: copied ${copied} files`);
